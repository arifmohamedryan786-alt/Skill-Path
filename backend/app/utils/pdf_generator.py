import io
from reportlab.lib.pagesizes import letter
from reportlab.lib import colors
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, HRFlowable
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle

def generate_passport_pdf(
    student_name: str,
    target_career: str,
    readiness_pct: float,
    verified_skills: list[dict],
    public_url: str
) -> bytes:
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=letter,
        rightMargin=40,
        leftMargin=40,
        topMargin=40,
        bottomMargin=40
    )

    styles = getSampleStyleSheet()
    
    # Custom palette styles
    primary_color = colors.HexColor("#0F6E68")
    ink_color = colors.HexColor("#1C2B2A")
    muted_color = colors.HexColor("#5E6B69")
    bg_tint = colors.HexColor("#E3F1EF")
    
    title_style = ParagraphStyle(
        'PassportTitle',
        parent=styles['Heading1'],
        fontName='Helvetica-Bold',
        fontSize=24,
        textColor=primary_color,
        spaceAfter=6
    )
    
    subtitle_style = ParagraphStyle(
        'PassportSubtitle',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=12,
        textColor=muted_color,
        spaceAfter=15
    )
    
    meta_style = ParagraphStyle(
        'PassportMeta',
        parent=styles['Normal'],
        fontName='Helvetica-Bold',
        fontSize=13,
        textColor=ink_color,
        spaceAfter=10
    )

    body_style = ParagraphStyle(
        'PassportBody',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=10,
        textColor=ink_color
    )

    story = []
    
    story.append(Paragraph("SkillPath Verified Skill Passport", title_style))
    story.append(Paragraph("Tamper-Evident Cryptographic Credential Record", subtitle_style))
    story.append(HRFlowable(width="100%", thickness=1.5, color=primary_color, spaceBefore=4, spaceAfter=15))
    
    # Summary info
    info_text = f"<b>Student:</b> {student_name} &nbsp;&nbsp;|&nbsp;&nbsp; <b>Target Career:</b> {target_career} &nbsp;&nbsp;|&nbsp;&nbsp; <b>Readiness:</b> {readiness_pct:.1f}%"
    story.append(Paragraph(info_text, meta_style))
    story.append(Spacer(1, 10))

    # Table of verified skills
    table_data = [
        ["Skill Name", "Level", "Exam Score", "Verification Hash (SHA-256)", "Status"]
    ]
    
    for sk in verified_skills:
        table_data.append([
            sk.get("name", "Skill"),
            f"Level {sk.get('level', 1)}",
            f"{sk.get('score', 80.0):.1f}%",
            sk.get("hash", "n/a")[:18] + "...",
            "VERIFIED"
        ])
    
    if len(table_data) == 1:
        table_data.append(["No verified skills yet", "-", "-", "-", "IN PROGRESS"])

    t = Table(table_data, colWidths=[130, 60, 80, 180, 80])
    t.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, 0), bg_tint),
        ('TEXTCOLOR', (0, 0), (-1, 0), primary_color),
        ('FONTNAME', (0, 0), (-1, 0), 'Helvetica-Bold'),
        ('FONTSIZE', (0, 0), (-1, -1), 9),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 6),
        ('TOPPADDING', (0, 0), (-1, -1), 6),
        ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor("#E3E1DA")),
        ('ALIGN', (1, 0), (2, -1), 'CENTER'),
        ('ALIGN', (4, 0), (4, -1), 'CENTER'),
        ('TEXTCOLOR', (4, 1), (4, -1), colors.HexColor("#2F8F5B")),
    ]))
    
    story.append(t)
    story.append(Spacer(1, 20))
    story.append(Paragraph(f"<b>Verification Link:</b> <font color='#0F6E68'>{public_url}</font>", body_style))
    story.append(Spacer(1, 8))
    story.append(Paragraph("This certificate was cryptographically generated by SkillPath. Each verified skill record is hashed against immutable assessment and project logs.", subtitle_style))
    
    doc.build(story)
    buffer.seek(0)
    return buffer.getvalue()


def generate_career_guide_pdf(
    student_name: str,
    degree_info: str,
    target_career: str,
    guide_content: dict
) -> bytes:
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=letter,
        rightMargin=40,
        leftMargin=40,
        topMargin=40,
        bottomMargin=40
    )

    styles = getSampleStyleSheet()
    primary_color = colors.HexColor("#0F6E68")
    ink_color = colors.HexColor("#1C2B2A")
    muted_color = colors.HexColor("#5E6B69")

    title_style = ParagraphStyle(
        'GuideTitle',
        parent=styles['Heading1'],
        fontName='Helvetica-Bold',
        fontSize=22,
        textColor=primary_color,
        spaceAfter=4
    )
    
    subhead_style = ParagraphStyle(
        'GuideSubhead',
        parent=styles['Heading2'],
        fontName='Helvetica-Bold',
        fontSize=14,
        textColor=primary_color,
        spaceBefore=12,
        spaceAfter=6
    )

    body_style = ParagraphStyle(
        'GuideBody',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=10,
        leading=14,
        textColor=ink_color,
        spaceAfter=8
    )

    story = []
    story.append(Paragraph(f"SkillPath Career Guide: {target_career}", title_style))
    story.append(Paragraph(f"Prepared for {student_name} ({degree_info})", body_style))
    story.append(HRFlowable(width="100%", thickness=1.5, color=primary_color, spaceBefore=4, spaceAfter=12))

    sections = [
        ("1. Where You Stand Today", guide_content.get("where_you_stand", "You are at the start of your journey.")),
        ("2. Top Recommended Careers", guide_content.get("top_careers_summary", "Based on your background and discovery answers.")),
        ("3. Essential Skills & Learning Sequence", guide_content.get("skills_sequence", "Master core foundations first before moving to specialized frameworks.")),
        ("4. Hands-on Projects (Portfolio Builder)", guide_content.get("projects_summary", "Build practical real-world projects to showcase on GitHub.")),
        ("5. Internship & Job Application Strategy", guide_content.get("internship_strategy", "Target internships aligned with your current year of study.")),
        ("6. 12-Month Progression Plan", guide_content.get("twelve_month_plan", "Month-by-month roadmap milestones.")),
        ("7. Next 7 Days: Where to Start Today", guide_content.get("next_7_days", "Take your first step this week with bite-sized daily tasks."))
    ]

    for title, text in sections:
        story.append(Paragraph(title, subhead_style))
        story.append(Paragraph(str(text), body_style))
        story.append(Spacer(1, 4))

    doc.build(story)
    buffer.seek(0)
    return buffer.getvalue()

